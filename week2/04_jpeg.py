"""
Копия с копии: что JPEG делает с картинкой за тысячу пересохранений.

Открываем картинку, сохраняем. Открываем то, что сохранилось, сохраняем снова.
И так тысячу раз. Картинку не двигаем, не крутим и не меняем в размере —
трогаем только одно число, качество сжатия.

На диске всё время лежит одна рабочая копия, её и перезаписываем, поэтому
мусора не остаётся. В папку откладываются только круги из списка KEEP.

Что выяснилось на опыте. Если качество постоянное, картинка замирает: уже
через 3–7 кругов файл становится байт в байт прежним и дальше не меняется
вообще. Если качество случайное, всё зависит от РАЗБРОСА, а не от самой
случайности и не от того, низкое оно или высокое. Разница с оригиналом
после 1000 кругов, по шкале от 0 до 255:

    постоянное 70      0.74   замирает на 3 круге, ничего не происходит
    случайное 88..92   1.03   глазом не видно
    случайное 70..75   1.21   глазом не видно
    случайное 60..90   9.92   уже заметно
    случайное 30..95  25.41   картинка рассыпается на квадраты

Узкая полоса даёт картинке сесть в почти неподвижную точку. Широкая заставляет
каждый раз пересчитывать её по новой таблице, и ошибки копятся.

Запускать из корня проекта:  python week2/04_jpeg.py
"""
import os
import random
from PIL import Image

SOURCE = "/Users/viktorkertanov/Downloads/1665_Girl_with_a_Pearl_Earring.jpg"
OUT = "week2/pearl"
WORK = OUT + "/_work.jpg"

ROUNDS = 1000

# Единственное, что мы крутим. Поставьте 88 и 92 — и увидите, что ничего
# не происходит. Чем шире полоса, тем быстрее разваливается картинка.
QUALITY_LOW = 30
QUALITY_HIGH = 95

KEEP = [1, 2, 5, 10, 20, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000]

os.makedirs(OUT, exist_ok=True)

image = Image.open(SOURCE)
print("Исходник:", image.size, image.mode)

image = image.convert("RGB")      # в JPEG нет прозрачности
image.save(WORK, quality=QUALITY_HIGH)

previous = b""
same = 0

for i in range(1, ROUNDS + 1):
    quality = random.randint(QUALITY_LOW, QUALITY_HIGH)

    image = Image.open(WORK)
    image.load()                  # дочитываем файл, иначе перезапись его испортит
    image.save(WORK, quality=quality)

    with open(WORK, "rb") as file:
        data = file.read()

    if data == previous:
        same = same + 1           # файл повторился байт в байт
    previous = data

    if i in KEEP:
        name = OUT + "/gen_" + str(i).zfill(4) + ".jpg"
        with open(name, "wb") as file:     # копируем байтами, без лишнего пересохранения
            file.write(data)
        print("круг", str(i).rjust(4), "| качество", str(quality).rjust(2),
              "|", str(len(data) // 1024).rjust(4), "КБ")

os.remove(WORK)                   # рабочую копию не храним
print()
print("Кругов, на которых файл вообще не изменился:", same, "из", ROUNDS)
print("Кадров в папке", OUT + ":", len(KEEP))
